"""Write the LaTeX tables and macros of the natural-distribution section (paper v7).

Inputs: scfp_runs/paper_v7/results.json (scfp_bench.experiments.paper_v7) and the hidden-state
probe results in each run's signals_summary.json. No number is typed by hand.

  PYTHONPATH=. python -m scfp_bench.experiments.make_tables_v7 --out ../../../paper_tables
"""

import argparse
import json
import os

GENS = [("qwen2.5-0.5b", "Qwen2.5-0.5B"), ("qwen2.5-1.5b", "Qwen2.5-1.5B"),
        ("smollm2-1.7b", "SmolLM2-1.7B"), ("qwen2.5-3b", "Qwen2.5-3B")]
MACRO = {"qwen2.5-0.5b": "QA", "qwen2.5-1.5b": "QB", "smollm2-1.7b": "SM", "qwen2.5-3b": "QC", "pooled": "Pool"}
PRED = [("text_tfidf", "TF-IDF + LR (text)"), ("signals_noverifier", "Generator signals, no verifier"),
        ("signals", "Generator signals + verifier"), ("signals_gbm", "Gradient boosting on signals + verifier"),
        ("concat_text_signals", "Text and signals + verifier (one linear model)")]
PMAC = {"text_tfidf": "Tfidf", "signals_noverifier": "SigNoVer", "signals": "Sig", "signals_gbm": "Gbm",
        "concat_text_signals": "Concat"}
SRC = [("gsm8k", "GSM8K"), ("strategyqa", "StrategyQA"), ("logiqa", "LogiQA")]
SMAC = {"gsm8k": "Gsm", "strategyqa": "Sqa", "logiqa": "Logiqa"}  # macro names cannot contain digits
HIDDEN = {"qwen2.5-0.5b": "scfp_runs/signals_mac_q05_big/results/signals_summary.json",
          "qwen2.5-1.5b": "scfp_runs/signals_kaggle/results_kaggle_v6/signals_summary.json",
          "smollm2-1.7b": "scfp_runs/signals_kaggle/results_kaggle_v6/signals_summary.json",
          "qwen2.5-3b": "scfp_runs/signals_kaggle/results_kaggle_v6/signals_summary.json"}


def write(out, name, body):
    with open(os.path.join(out, name), "w") as f:
        f.write("% generated by scfp_bench.experiments.make_tables_v7 -- do not edit by hand\n" + body)


def p_fmt(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def p_rel(p):
    """For prose, inside math mode: $p \\vXPTfidf$ gives p < 0.001 or p = 0.019."""
    return "< 0.001" if p < 0.001 else f"= {p:.3f}"


def auc_ci(r):
    return f"{r['auc']:.3f} [{r['ci']['auc'][0]:.3f}, {r['ci']['auc'][1]:.3f}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="scfp_runs/paper_v7/results.json")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    R = json.load(open(a.results))
    M, C = R["main"], {}  # C: macros

    # --- outcomes of the natural set, per generator
    rows = []
    for g, name in GENS:
        o = R["outcomes"][f"natural|{g}"]
        gen = o["n"] + o["excluded"]
        rows.append(f"{name} & {gen:,} & {o['n']:,} ({100 * o['n'] / gen:.1f}\\%) & {100 * o['r0_acc']:.1f}\\% & "
                    f"{100 * o['rf_acc']:.1f}\\% & {100 * o['repair']:.1f}\\% & {100 * o['harm']:.1f}\\% & "
                    f"{100 * (1 - o['rf_acc']):.1f}\\% \\\\")
        m = MACRO[g]
        C.update({f"nat{m}Gen": f"{gen:,}", f"nat{m}Kept": f"{o['n']:,}", f"nat{m}Excl": f"{100 * o['excluded'] / gen:.1f}",
                  f"nat{m}RzeroAcc": f"{100 * o['r0_acc']:.1f}", f"nat{m}RfAcc": f"{100 * o['rf_acc']:.1f}",
                  f"nat{m}Repair": f"{100 * o['repair']:.1f}", f"nat{m}Harm": f"{100 * o['harm']:.1f}",
                  f"nat{m}Fail": f"{100 * (1 - o['rf_acc']):.1f}",
                  f"nat{m}KeptStrategyqa": str(o["by_source"]["strategyqa"]),
                  f"nat{m}GenStrategyqa": str(o["by_source"]["strategyqa"] + o["excluded_by_source"]["strategyqa"])})
    tot = sum(R["outcomes"][f"natural|{g}"]["n"] for g, _ in GENS)
    C["natTotalKept"] = f"{tot:,}"
    write(a.out, "tab_nat_outcomes.tex",
          "\\begin{tabular}{lrrrrrrr}\n\\toprule\nGenerator & Generated & Kept & $R_0$ correct & $R_f$ correct & "
          "Repair & Harm & Final wrong \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # --- main failure-prediction table (natural set, paper label)
    rows = []
    for g, name in GENS + [("pooled", "Pooled (four generators)")]:
        key = f"natural|{g}"
        base = M[f"{key}|text_tfidf"]
        rows.append(f"\\multicolumn{{5}}{{l}}{{\\textit{{{name}}}: $n = {base['n']:,}$, majority class "
                    f"{100 * base['majority']:.1f}\\%}} \\\\")
        best = max(PRED, key=lambda x: M[f"{key}|{x[0]}"]["auc"])[0]
        for p, pname in PRED:
            r = M[f"{key}|{p}"]
            auc = auc_ci(r)
            if p == best:
                auc = f"\\textbf{{{r['auc']:.3f}}} [{r['ci']['auc'][0]:.3f}, {r['ci']['auc'][1]:.3f}]"
            pt = "--" if p == "text_tfidf" else p_fmt(r["p_vs_tfidf"])
            rows.append(f"\\quad {pname} & {auc} & {100 * r['accuracy']:.1f}\\% & {r['macro_f1']:.3f} & {pt} \\\\")
            m, pm = MACRO[g], PMAC[p]
            C.update({f"v{m}{pm}AUC": f"{r['auc']:.3f}", f"v{m}{pm}AUCLo": f"{r['ci']['auc'][0]:.3f}",
                      f"v{m}{pm}AUCHi": f"{r['ci']['auc'][1]:.3f}", f"v{m}{pm}Acc": f"{100 * r['accuracy']:.1f}",
                      f"v{m}{pm}Fone": f"{r['macro_f1']:.3f}", f"v{m}{pm}PMaj": p_rel(r["p_vs_majority"])})
            if p != "text_tfidf":
                C[f"v{m}{pm}PTfidf"] = p_rel(r["p_vs_tfidf"])
        C[f"v{MACRO[g]}Maj"] = f"{100 * base['majority']:.1f}"
        C[f"v{MACRO[g]}N"] = f"{base['n']:,}"
        rows.append("\\midrule")
    rows.pop()
    write(a.out, "tab_nat_main.tex",
          "\\begin{tabular}{lcccc}\n\\toprule\nPredictor & AUC [95\\% CI] & Accuracy & Macro-F1 & $p$ vs TF-IDF \\\\\n"
          "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # --- verifier by source
    rows = []
    for g, name in GENS:
        cells = []
        for s, _ in SRC:
            k = f"natural|{g}|{s}"
            if f"{k}|signals" not in R["by_source"]:
                cells += ["--"] * 3
                continue
            t, n, v = (R["by_source"][f"{k}|{x}"] for x in ("text_tfidf", "signals_noverifier", "signals"))
            cells += [f"{t['auc']:.3f}", f"{n['auc']:.3f}", f"{v['auc']:.3f}"]
            m = MACRO[g]
            C.update({f"src{m}{SMAC[s]}N": str(v["n"]), f"src{m}{SMAC[s]}NoVer": f"{n['auc']:.3f}",
                      f"src{m}{SMAC[s]}Ver": f"{v['auc']:.3f}", f"src{m}{SMAC[s]}Tfidf": f"{t['auc']:.3f}",
                      f"src{m}{SMAC[s]}VerAcc": f"{100 * v['accuracy']:.1f}",
                      f"src{m}{SMAC[s]}Maj": f"{100 * v['majority']:.1f}"})
        rows.append(f"{name} & " + " & ".join(cells) + " \\\\")
    write(a.out, "tab_nat_verifier.tex",
          "\\begin{tabular}{l" + "ccc" * 3 + "}\n\\toprule\n & " +
          " & ".join(f"\\multicolumn{{3}}{{c}}{{{n}}}" for _, n in SRC) + " \\\\\n" +
          "".join(f"\\cmidrule(lr){{{2 + 3 * i}-{4 + 3 * i}}}" for i in range(3)) + "\n" +
          "Generator" + " & Text & Sig. & +Ver." * 3 + " \\\\\n\\midrule\n" + "\n".join(rows) +
          "\n\\bottomrule\n\\end{tabular}\n")

    # --- sub-tasks
    rows = []
    for g, name in GENS:
        k = f"natural|{g}"
        cells = [f"{M[f'{k}|signals_gbm']['auc']:.3f}"]
        for t in ("r0_wrong", "changed", "repair", "harm"):
            r = R["subtasks"].get(f"{k}|{t}")
            cells.append(f"{r['auc']:.3f} ({r['n']:,})" if r else "--")
            if r:
                C[f"sub{MACRO[g]}{dict(r0_wrong='Rzero', changed='Changed', repair='Repair', harm='Harm')[t]}"] = f"{r['auc']:.3f}"
        rows.append(f"{name} & " + " & ".join(cells) + " \\\\")
    write(a.out, "tab_nat_subtasks.tex",
          "\\begin{tabular}{lccccc}\n\\toprule\nGenerator & Final wrong & $R_0$ wrong & Answer changes & "
          "Repair & Harm \\\\\n & (all) & (all) & (all) & ($R_0$ wrong) & ($R_0$ correct) \\\\\n\\midrule\n" +
          "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # --- difficulty filter: SCFP v1 vs natural set, same generator
    rows = []
    for g, name in GENS:
        if f"v1|{g}|text_tfidf" not in M:
            continue
        v1t, v1s = M[f"v1|{g}|text_tfidf"], M[f"v1|{g}|signals"]
        nt, ns = M[f"natural|{g}|text_tfidf"], M[f"natural|{g}|signals"]
        rows.append(f"{name} & {v1t['n']} & {v1t['auc']:.3f} & {v1s['auc']:.3f} & {nt['n']:,} & "
                    f"{nt['auc']:.3f} & {ns['auc']:.3f} \\\\")
        m = MACRO[g]
        C.update({f"filt{m}VoneN": str(v1t["n"]), f"filt{m}VoneTfidf": f"{v1t['auc']:.3f}",
                  f"filt{m}VoneSig": f"{v1s['auc']:.3f}",
                  f"filt{m}VoneTfidfLo": f"{v1t['ci']['auc'][0]:.3f}", f"filt{m}VoneTfidfHi": f"{v1t['ci']['auc'][1]:.3f}"})
    write(a.out, "tab_filter_effect.tex",
          "\\begin{tabular}{lrccrcc}\n\\toprule\n & \\multicolumn{3}{c}{SCFP v1 (difficulty-filtered)} & "
          "\\multicolumn{3}{c}{Natural set} \\\\\n\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\n"
          "Generator & $n$ & Text AUC & Signals AUC & $n$ & Text AUC & Signals AUC \\\\\n\\midrule\n" +
          "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # --- hidden-state probes (last layer, end of R0), from each run's evaluate stage
    for g, _ in GENS:
        h = json.load(open(HIDDEN[g]))["natural"]["rf_wrong"][g]
        C[f"hid{MACRO[g]}AUC"] = f"{h['hidden_last_R0']['auc']:.3f}"
        C[f"hid{MACRO[g]}MidAUC"] = f"{h['hidden_mid_F']['auc']:.3f}"

    write(a.out, "macros_v7.tex", "".join(f"\\providecommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(C.items())))
    json.dump(C, open(os.path.join(a.out, "numbers_v7.json"), "w"), indent=1, sort_keys=True)
    print(f"wrote {len(C)} macros and 5 tables to {a.out}")


if __name__ == "__main__":
    main()
