def write(out, name, body):
    with open(os.path.join(out, name), "w") as f:
        f.write("% generated by scfp_bench.experiments.make_tables_revision -- do not edit by hand\n" + body)


def pct(x):
    return f"{100 * x:.1f}"


def ci_pct(ci):
    return f"[{pct(ci[0])}, {pct(ci[1])}]"


def stack(a, b):
    """Two lines in one cell (value over interval), so wide tables fit at footnotesize."""
    return f"\\makecell{{{a}\\\\{{{b}}}}}"


def pval(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


