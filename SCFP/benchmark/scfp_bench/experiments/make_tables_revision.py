"""Tables, figures and macros added in the major revision, from results/revision/ (no number typed by hand).

    python -m scfp_bench.experiments.make_tables_revision --results ../../results/revision --out ../../../paper_tables

Each workstream adds a section below; a section is skipped while its result files do not exist yet.
Macros go to macros_rev.tex (\\providecommand) and numbers_rev.json.
"""

import argparse
import json
import os
import shutil


def write(out, name, body):
    with open(os.path.join(out, name), "w") as f:
        f.write("% generated by scfp_bench.experiments.make_tables_revision -- do not edit by hand\n" + body)


def pct(x):
    return f"{100 * x:.1f}"


def ci_pct(ci):
    return f"[{pct(ci[0])}, {pct(ci[1])}]"


def pval(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def m4(res_dir, out, M):
    p = os.path.join(res_dir, "m4", "routing_m4.json")
    if not os.path.exists(p):
        return
    R = json.load(open(p))
    P = R["policies"]
    order = ["No correction (R0 only)", "Always Intrinsic", "Always Extrinsic", "Agreement tool",
             "Confidence-based", "Dynamic (our predictor)", "Agreement tool + human", "Random (uniform, expected)",
             "Always Human (oracle)"]
    label = {"No correction (R0 only)": "No correction (return $R_0$)",
             "Agreement tool": "Agreement tool ($R_0$ if PoT agrees, else PoT)",
             "Agreement tool + human": "Agreement tool, disagreements to human$^\\dagger$",
             "Confidence-based": "Confidence-based router", "Dynamic (our predictor)": "Dynamic router (DeBERTa)",
             "Always Human (oracle)": "Always Human (oracle)$^\\dagger$",
             "Random (uniform, expected)": "Random (uniform, expected)$^\\dagger$"}
    lines = []
    for n in order:
        v = P[n]
        acc = pct(v["accuracy"]) + (f" {ci_pct(v['accuracy_ci95'])}" if v["accuracy_ci95"] else "")
        d = v["paired_vs_r0_only"]
        dd = "--" if d is None else f"{100 * d['diff']:+.1f} {ci_pct(d['ci95'])}"
        lines.append(f"{label.get(n, n)} & {acc} & {dd} & {v['relative_cost']:.2f}$\\times$ & "
                     f"{v['latency_s']:.1f} & {pct(v['share_human'])}\\% \\\\")
    write(out, "tab_routing_rev.tex",
          "\\begin{tabular}{@{}lccccc@{}}\n\\toprule\nStrategy & Accuracy (\\%) [95\\% CI] & "
          "$\\Delta$ vs no correction (pp) [95\\% CI] & Cost & Latency (s) & To human \\\\\n\\midrule\n"
          + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")

    # secondary table: Overall Score at the paper's setting, and which policy wins across settings
    S = R["sensitivity"]
    names = [n for n in order if any(v.get(n) for v in S["wins_by_assumption"].values()) or n in
             ("Dynamic (our predictor)", "Confidence-based")]
    cols = list(S["wins_by_assumption"])
    rows = []
    for n in order:
        wins = [S["wins_by_assumption"][c][n] for c in cols]
        rows.append(f"{label.get(n, n)} & {P[n]['overall_score']:.3f} & " + " & ".join(map(str, wins))
                    + f" & {S['wins'][n]} \\\\")
    per = S["n_settings"] // len(cols)
    write(out, "tab_routing_sensitivity.tex",
          "\\begin{tabular}{@{}lc" + "c" * len(cols) + "c@{}}\n\\toprule\n & Overall Score & "
          f"\\multicolumn{{{len(cols)}}}{{c}}{{Settings won (of {per} weight vectors), by assumed human cost/latency}} & Total \\\\\n"
          f"\\cmidrule(lr){{3-{2 + len(cols)}}}\nStrategy & (paper weights) & "
          + " & ".join(c.replace("x/", "$\\times$/") for c in cols) + f" & (of {S['n_settings']}) \\\\\n\\midrule\n"
          + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    del names

    for f in ("fig_pareto.pdf", "fig_risk_coverage.pdf"):
        shutil.copy(os.path.join(res_dir, "m4", f), os.path.join(out, "rev_" + f))

    r0, intr, ext = P["No correction (R0 only)"], P["Always Intrinsic"], P["Always Extrinsic"]
    agh, dyn = P["Agreement tool + human"], P["Dynamic (our predictor)"]
    rc = R["risk_coverage"]
    M.update({
        "rtRzeroAcc": pct(r0["accuracy"]), "rtRzeroAccLo": pct(r0["accuracy_ci95"][0]),
        "rtRzeroAccHi": pct(r0["accuracy_ci95"][1]), "rtRzeroCost": f"{r0['relative_cost']:.2f}",
        "rtRzeroLat": f"{r0['latency_s']:.1f}",
        "rtIntAcc": pct(intr["accuracy"]), "rtExtAcc": pct(ext["accuracy"]),
        "rtRzeroVsInt": f"{100 * intr['paired_vs_r0_only']['diff'] * -1:.1f}",
        "rtRzeroVsIntLo": f"{-100 * intr['paired_vs_r0_only']['ci95'][1]:.1f}",
        "rtRzeroVsIntHi": f"{-100 * intr['paired_vs_r0_only']['ci95'][0]:.1f}",
        "rtRzeroVsExt": f"{-100 * ext['paired_vs_r0_only']['diff']:.1f}",
        "rtRzeroVsExtLo": f"{-100 * ext['paired_vs_r0_only']['ci95'][1]:.1f}",
        "rtRzeroVsExtHi": f"{-100 * ext['paired_vs_r0_only']['ci95'][0]:.1f}",
        "rtRzeroVsExtP": pval(R["paired"]["No correction (R0 only) vs Always Extrinsic"]["mcnemar_p"]),
        "rtRzeroVsIntP": pval(R["paired"]["No correction (R0 only) vs Always Intrinsic"]["mcnemar_p"]),
        "rtAgrAcc": pct(P["Agreement tool"]["accuracy"]), "rtAgrCost": f"{P['Agreement tool']['relative_cost']:.2f}",
        "rtAgrHumAcc": pct(agh["accuracy"]), "rtAgrHumCost": f"{agh['relative_cost']:.2f}",
        "rtAgrHumShare": pct(agh["share_human"]), "rtAgrHumLat": f"{agh['latency_s']:.1f}",
        "rtProgAnswered": str(R["agreement"]["program_answered"]),
        "rtProgAgrees": str(R["agreement"]["program_agrees_with_r0"]),
        "rtAgrDiffExt": str(R["agreement"]["agreement_tool_answers_differ_from_extrinsic"]),
        "rtDynAcc": pct(dyn["accuracy"]),
        "rtAurcDeberta": f"{rc['DeBERTa p_fail']['aurc']:.3f}",
        "rtAurcDebertaLo": f"{rc['DeBERTa p_fail']['aurc_ci95'][0]:.3f}",
        "rtAurcDebertaHi": f"{rc['DeBERTa p_fail']['aurc_ci95'][1]:.3f}",
        "rtAurcDebertaDiffLo": f"{rc['DeBERTa p_fail']['diff_vs_random_ci95'][0]:.3f}",
        "rtAurcDebertaDiffHi": f"{rc['DeBERTa p_fail']['diff_vs_random_ci95'][1]:.3f}",
        "rtAurcConf": f"{rc['Critique confidence']['aurc']:.3f}",
        "rtAurcRandom": f"{rc['Random (expected)']['aurc']:.3f}", "rtAurcOracle": f"{rc['Oracle']['aurc']:.3f}",
        "rtSensN": str(S["n_settings"]), "rtSensRzeroWins": str(S["wins"]["No correction (R0 only)"]),
        "rtSensAgrHumWins": str(S["wins"]["Agreement tool + human"]),
        "rtSensHumWins": str(S["wins"]["Always Human (oracle)"]),
        "rtSensDynBeatsFixed": str(S["dynamic_beats_best_fixed"]),
        "rtSweepNdDyn": str(R["sweep_points_not_dominated"]["Dynamic (our predictor)"]),
        "rtSweepNdConf": str(R["sweep_points_not_dominated"]["Confidence-based"]),
        "rtSweepTotal": str(R["sweep_points_total"]),
        "rtSweepNdMinHum": f"{100 * R['sweep_not_dominated_min_share_human']:.0f}",
    })


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="../../results/revision")
    ap.add_argument("--out", default="../../../paper_tables")
    a = ap.parse_args()
    M = {}
    for section in (m4,):
        section(a.results, a.out, M)
    write(a.out, "macros_rev.tex", "".join(f"\\providecommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(M.items())))
    json.dump(M, open(os.path.join(a.out, "numbers_rev.json"), "w"), indent=1, sort_keys=True)
    print(f"wrote {len(M)} revision macros to {a.out}")


if __name__ == "__main__":
    main()
