"""Write every data-derived LaTeX table of the paper from the run directory.

No number in these tables is typed by hand. Re-run after any change to the
data or predictions and \\input{} the files into the manuscript.

  python -m scfp_bench.experiments.make_tables --config configs/laptop_local.yaml --out ../../../paper_tables
"""

import argparse
import json
import os
import re
from collections import Counter

import yaml

from ..stages import read_jsonl
from .data import load_splits

SRC = {"gsm8k": "GSM8K", "strategyqa": "StrategyQA", "logiqa": "LogiQA"}
CELLS = ["right->right", "wrong->right", "right->wrong", "wrong->wrong"]
CELL_TEX = {"right->right": r"correct $\rightarrow$ correct", "wrong->right": r"wrong $\rightarrow$ correct",
            "right->wrong": r"correct $\rightarrow$ wrong", "wrong->wrong": r"wrong $\rightarrow$ wrong"}
NAMES = {"majority": "Majority class", "random": "Random (train prior)", "length": "Length heuristic",
         "confidence": "Confidence heuristic (critique log-prob)", "tfidf_lr": "TF-IDF + logistic regression"}


def esc(s):
    for a_, b_ in [("\u2019", "'"), ("\u2018", "'"), ("\u201c", '"'), ("\u201d", '"'), ("\u2013", "-"),
                   ("\u2014", "-"), ("\u00d7", "x"), ("\u2212", "-")]:
        s = s.replace(a_, b_)
    s = s.encode("ascii", "replace").decode()
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in [("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")]:
        s = s.replace(a, b)
    return re.sub(r"\s+", " ", s).strip()


def short(s, n=220):
    """Keep the start and the last few words (where final answers are), cut at word boundaries."""
    s = re.sub(r"\s+", " ", s).strip()
    if len(s) <= n:
        return s
    head = s[: n - 40].rsplit(" ", 1)[0]
    tail = s[-35:].split(" ", 1)[-1]
    return f"{head} [...] {tail}"


def pct(a, b):
    return f"{100 * a / b:.1f}\\%" if b else "--"


def write(out, name, body):
    with open(os.path.join(out, name), "w") as f:
        f.write("% generated by scfp_bench.experiments.make_tables -- do not edit by hand\n" + body)


ENCODERS = [("deberta-scfp", "Our model (segment-aware DeBERTa-v3-small)"),
            ("deberta-plain", "DeBERTa-v3-small (plain)"), ("roberta-base", "RoBERTa-base"),
            ("bert-base", "BERT-base")]
ABLATIONS = [("deberta-scfp", "Full model", "--"),
             ("abl-no-segments", "No segment embeddings (and full attention)", "\\texttt{--no-segments}"),
             ("abl-no-attention", "No segment-aware attention layer", "\\texttt{--no-special-attention}"),
             ("abl-inputs-P-R0", "Prompt + initial response only", "\\texttt{--inputs P,R0}"),
             ("abl-inputs-P-F", "Prompt + critique only", "\\texttt{--inputs P,F}"),
             ("abl-inputs-R0-F", "Initial response + critique only", "\\texttt{--inputs R0,F}"),
             ("abl-deberta-xsmall", "DeBERTa-v3-xsmall backbone", "\\texttt{--model microsoft/deberta-v3-xsmall}")]
TBD = "\\TBD"


def _res(res_dir, name):
    p = os.path.join(res_dir, f"{name}.json")
    return json.load(open(p)) if os.path.exists(p) else None


def encoder_tables(rd, res_dir, out, numbers):
    """Encoder, ablation and cross-model tables; missing runs appear as \\TBD."""
    rows = []
    for name, label in ENCODERS:
        r = _res(res_dir, name)
        if r is None:
            rows.append(f"{label} & {TBD} & {TBD} & {TBD} & {TBD} \\\\")
            continue
        te, ci = r["test"], r["test"]["ci95"]["accuracy"]
        multi = r.get("test_multiclass", {}).get("macro_f1")
        rows.append(f"{label} & {te['accuracy']:.3f} [{ci[0]:.3f}, {ci[1]:.3f}] & {te['macro_f1']:.3f} & "
                    f"{te.get('auc', float('nan')):.3f} & {f'{multi:.3f}' if multi is not None else '--'} \\\\")
        numbers.setdefault("encoders", {})[name] = te
    write(out, "tab_encoder_results.tex", r"""\begin{tabular}{@{}lcccc@{}}
\toprule
\textbf{Model} & \textbf{Binary Accuracy [95\% CI]} & \textbf{Binary Macro F1} & \textbf{AUC-ROC} & \textbf{Multi-class Macro F1} \\
\midrule
""" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    rows = []
    for name, label, switch in ABLATIONS:
        r = _res(res_dir, name)
        acc = f"{r['test']['accuracy']:.3f}" if r else TBD
        f1 = f"{r['test']['macro_f1']:.3f}" if r else TBD
        rows.append(f"{label} & {switch} & {acc} & {f1} \\\\")
    write(out, "tab_ablations.tex", r"""\begin{tabular}{@{}llcc@{}}
\toprule
\textbf{Configuration} & \textbf{Script switch} & \textbf{Accuracy} & \textbf{Macro F1} \\
\midrule
""" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    p = os.path.join(rd, "predictions", "xmodel-qwen-to-all__binary.jsonl")
    preds = read_jsonl(p) if os.path.exists(p) else []
    rows = []
    for label, models_ in [("Qwen2.5 (same family as training)", ("qwen2.5-0.5b", "qwen2.5-1.5b")),
                           ("SmolLM2-1.7B (unseen family)", ("smollm2-1.7b",))]:
        sub = [r for r in preds if r["source_model"] in models_]
        n = sum(1 for r in load_splits(rd)["test"] if r["source_model"] in models_)
        if sub:
            from .metrics import bootstrap, summarize
            y, yp = [r["y_true"] for r in sub], [r["y_pred"] for r in sub]
            m, ci = summarize(y, yp), bootstrap(y, yp)["accuracy"]
            rows.append(f"{label} & {n} & {m['accuracy']:.3f} [{ci[0]:.3f}, {ci[1]:.3f}] & {m['macro_f1']:.3f} \\\\")
        else:
            rows.append(f"{label} & {n} & {TBD} & {TBD} \\\\")
    write(out, "tab_cross_model.tex", r"""\begin{tabular}{lccc}
\toprule
\textbf{Test traces} & \textbf{n} & \textbf{Binary Accuracy [95\% CI]} & \textbf{Macro F1} \\
\midrule
""" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def routing_and_macros(rd, res_dir, out, numbers):
    """Routing table and LaTeX macros for every number quoted in the prose."""
    from .metrics import mcnemar
    M = {}

    def put(key, val, fmt="{:.3f}"):
        M[key] = TBD if val is None else (fmt.format(val) if isinstance(val, (int, float)) else str(val))

    r = _res(res_dir, "routing")
    rows = []
    order = ["Always Intrinsic", "Always Extrinsic", "Always Human (oracle)", "Random (uniform, expected)",
             "Confidence-based", "Dynamic (our predictor)"]
    if r:
        for name in order:
            s = r["strategies"][name]
            ci = s.get("accuracy_ci95")
            acc = f"{100 * s['accuracy']:.1f}\\%" + (f" [{100 * ci[0]:.1f}, {100 * ci[1]:.1f}]" if ci else "")
            rows.append(f"{esc(name)} & {acc} & {s['latency_s']:.1f} & {s['relative_cost']:.2f}$\\times$ & "
                        f"{100 * s['share']['hum']:.1f}\\% & {s['overall_score']:.3f} \\\\")
        put("routeN", r["n_test"], "{}"); put("routeTune", r["n_tune"], "{}")
        put("routeUnit", r["cost_unit_tokens"], "{:.0f}")
        put("routeRzeroAcc", 100 * r["r0_accuracy_test"], "{:.1f}")
        put("routeRejected", r["program_rejected"], "{}"); put("routeProgErrors", r["program_errors"], "{}")
        for key, name in [("Int", "Always Intrinsic"), ("Ext", "Always Extrinsic"), ("Hum", "Always Human (oracle)"),
                          ("Rand", "Random (uniform, expected)"), ("Conf", "Confidence-based"), ("Dyn", "Dynamic (our predictor)")]:
            s = r["strategies"][name]
            put(f"route{key}Acc", 100 * s["accuracy"], "{:.1f}"); put(f"route{key}Lat", s["latency_s"], "{:.1f}")
            put(f"route{key}Cost", s["relative_cost"], "{:.2f}"); put(f"route{key}Hum", 100 * s["share"]["hum"], "{:.1f}")
            put(f"route{key}Score", s["overall_score"], "{:.3f}")
        th = r["strategies"]["Dynamic (our predictor)"]["thresholds"]
        put("routeTauLow", th[0], "{:.2f}"); put("routeTauHigh", th[1], "{:.2f}")
        numbers["routing"] = r["strategies"]
    else:
        rows = [f"{esc(n)} & {TBD} & {TBD} & {TBD} & {TBD} & {TBD} \\\\" for n in order]
    write(out, "tab_routing.tex", r"""\begin{tabular}{@{}lccccc@{}}
\toprule
\textbf{Strategy} & \textbf{Accuracy [95\% CI]} & \textbf{Latency (s)} & \textbf{Relative cost} & \textbf{Human share} & \textbf{Overall score} \\
\midrule
""" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # encoder headline numbers and paired tests against the TF-IDF and majority baselines
    def preds(name):
        p = os.path.join(rd, "predictions", f"{name}__binary.jsonl")
        return {x["trace_id"]: x for x in read_jsonl(p)} if os.path.exists(p) else None
    ours, tf, maj = preds("deberta-scfp"), preds("tfidf_lr"), preds("majority")
    e = _res(res_dir, "deberta-scfp")
    if e:
        put("ourAcc", 100 * e["test"]["accuracy"], "{:.1f}")
        put("ourAccLo", 100 * e["test"]["ci95"]["accuracy"][0], "{:.1f}"); put("ourAccHi", 100 * e["test"]["ci95"]["accuracy"][1], "{:.1f}")
        put("ourFone", e["test"]["macro_f1"]); put("ourAUC", e["test"].get("auc"))
        put("ourEpochs", len(e["log"]), "{}"); put("ourWall", e["wall_clock_s"] / 60, "{:.0f}")
    else:
        for k in ("ourAcc", "ourAccLo", "ourAccHi", "ourFone", "ourAUC", "ourEpochs", "ourWall"):
            put(k, None)
    for key, other in (("Tfidf", tf), ("Maj", maj)):
        if ours and other:
            ids = sorted(ours)
            y = [ours[i]["y_true"] for i in ids]
            m = mcnemar(y, [ours[i]["y_pred"] for i in ids], [other[i]["y_pred"] for i in ids])
            put(f"ourVs{key}P", m["p_value"])
        else:
            put(f"ourVs{key}P", None)
    an = _res(res_dir, "analysis")
    if an:
        at, la = an["attention"], an["latency"]
        put("attCorrect", at["critique_share_correct_mean"]); put("attCorrectSd", at["critique_share_correct_sd"])
        put("attIncorrect", at["critique_share_incorrect_mean"]); put("attIncorrectSd", at["critique_share_incorrect_sd"])
        put("attT", at["welch_t"], "{:.2f}"); put("attDf", at["welch_df"], "{:.1f}"); put("attP", at["p_value"])
        put("attNc", at["n_correct"], "{}"); put("attNi", at["n_incorrect"], "{}")
        for k in ("prompt", "R0", "critique"):
            put("attMean" + {"prompt": "P", "R0": "Rzero", "critique": "F"}[k], at["mean_shares_all"][k])
        put("latMedian", la["median_ms"], "{:.0f}"); put("latPninety", la["p90_ms"], "{:.0f}")
    else:
        for k in ("attCorrect", "attCorrectSd", "attIncorrect", "attIncorrectSd", "attT", "attDf", "attP",
                  "attNc", "attNi", "attMeanP", "attMeanRzero", "attMeanF", "latMedian", "latPninety"):
            put(k, None)
    body = "".join(f"\\providecommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(M.items()))
    write(out, "macros.tex", body)
    numbers["macros"] = M


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    cfg = yaml.safe_load(open(a.config))
    rd = cfg["run_dir"]
    os.makedirs(a.out, exist_ok=True)
    S = load_splits(rd)
    allr = [r for v in S.values() for r in v]
    excl = read_jsonl(os.path.join(rd, "excluded.jsonl"))
    fr = json.load(open(os.path.join(rd, "filter_report.json")))
    models = [m["name"] for m in cfg["models"] if m["name"] in cfg["generate"]["models"]]
    numbers = {}

    # --- filter yield
    rows = []
    for s, v in fr.items():
        rows.append(f"{SRC[s]} & {v['candidates']} & {v['in_band']} & {pct(v['in_band'], v['candidates'])} & {v['target']} & {v['selected']} \\\\")
    tot = {k: sum(v[k] for v in fr.values()) for k in ("candidates", "in_band", "target", "selected")}
    rows.append(r"\midrule" + f"\nTotal & {tot['candidates']} & {tot['in_band']} & {pct(tot['in_band'], tot['candidates'])} & {tot['target']} & {tot['selected']} \\\\")
    write(a.out, "tab_filter.tex", r"""\begin{tabular}{lrrrrr}
\toprule
Source & Candidates & In band & Yield & Target & Selected \\
\midrule
""" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    numbers["filter"] = tot

    # --- exclusion by model x source
    gen = Counter((r["source_model"], r["source"]) for r in allr) + Counter((r["source_model"], r["source"]) for r in excl)
    kept = Counter((r["source_model"], r["source"]) for r in allr)
    rows = []
    for m in models:
        cells = [f"{kept[(m, s)]}/{gen[(m, s)]}" for s in SRC]
        k, g = sum(kept[(m, s)] for s in SRC), sum(gen[(m, s)] for s in SRC)
        rows.append(f"{esc(m)} & " + " & ".join(cells) + f" & {k}/{g} ({pct(k, g)}) \\\\")
    K, G = len(allr), len(allr) + len(excl)
    rows.append(r"\midrule" + f"\nAll models & " + " & ".join(f"{sum(kept[(m, s)] for m in models)}/{sum(gen[(m, s)] for m in models)}" for s in SRC) + f" & {K}/{G} ({pct(K, G)}) \\\\")
    write(a.out, "tab_exclusion.tex", r"""\begin{tabular}{l""" + "c" * (len(SRC) + 1) + r"""}
\toprule
Generator & """ + " & ".join(SRC.values()) + r""" & All sources \\
\midrule
""" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    numbers["traces"] = {"generated": G, "kept": K, "excluded": len(excl)}

    # --- composition by split
    def line(label, f):
        return f"{label} & " + " & ".join(f(S[s]) for s in ("train", "val", "test")) + f" & {f(allr)} \\\\"
    body = [line("Traces", lambda v: str(len(v))),
            line("Source problems", lambda v: str(len({r['problem_id'] for r in v}))), r"\midrule",
            r"\multicolumn{5}{l}{\textit{Source}} \\"]
    body += [line(f"\\quad {SRC[s]}", lambda v, s=s: pct(sum(r['source'] == s for r in v), len(v))) for s in SRC]
    body += [r"\midrule", r"\multicolumn{5}{l}{\textit{Generator}} \\"]
    body += [line(f"\\quad {esc(m)}", lambda v, m=m: pct(sum(r['source_model'] == m for r in v), len(v))) for m in models]
    body += [r"\midrule", r"\multicolumn{5}{l}{\textit{Outcome ($R_0 \rightarrow R_f$)}} \\"]
    body += [line(f"\\quad {CELL_TEX[c]}", lambda v, c=c: pct(sum(r['outcome_cell'] == c for r in v), len(v))) for c in CELLS]
    body += [r"\midrule", line("Failure rate ($R_f$ wrong)", lambda v: pct(sum(r['label'] for r in v), len(v)))]
    write(a.out, "tab_composition.tex", r"""\begin{tabular}{lrrrr}
\toprule
 & Train & Validation & Test & Total \\
\midrule
""" + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n")
    numbers["splits"] = {s: {"traces": len(v), "problems": len({r['problem_id'] for r in v}),
                             "failure_rate": sum(r['label'] for r in v) / len(v)} for s, v in S.items()}
    numbers["outcomes"] = dict(Counter(r["outcome_cell"] for r in allr))

    # --- outcome cells by generator
    rows = []
    for m in models:
        R = [r for r in allr if r["source_model"] == m]
        c = Counter(r["outcome_cell"] for r in R)
        rows.append(f"{esc(m)} & {len(R)} & " + " & ".join(pct(c[x], len(R)) for x in CELLS) + f" & {pct(sum(r['label'] for r in R), len(R))} \\\\")
    write(a.out, "tab_outcomes_by_model.tex", r"""\begin{tabular}{lrrrrrr}
\toprule
Generator & Traces & """ + " & ".join(CELL_TEX[c] for c in CELLS) + r""" & Failure rate \\
\midrule
""" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # --- one real trace per outcome cell (first by trace_id in the test split, for reproducibility)
    rows = []
    for c in CELLS:
        cands = sorted([r for r in S["test"] if r["outcome_cell"] == c and r["source"] == "gsm8k"],
                       key=lambda r: r["trace_id"]) or sorted([r for r in S["test"] if r["outcome_cell"] == c],
                                                              key=lambda r: r["trace_id"])
        r = cands[0]
        rows.append(f"{CELL_TEX[c]} & {esc(r['source_model'])} & {esc(short(r['prompt'], 160))} (gold: {esc(r['gold'])}) & "
                    f"{esc(short(r['initial_response'], 180))} & {esc(short(r['critique'], 200))} & "
                    f"{esc(short(r['final_response'], 180))} \\\\ \\midrule")
        numbers.setdefault("example_trace_ids", {})[c] = r["trace_id"]
    rows[-1] = rows[-1].replace(r"\\ \midrule", r"\\")
    write(a.out, "tab_real_examples.tex", r"""\begin{tabular}{p{1.6cm}p{1.4cm}p{3.2cm}p{3.2cm}p{3.6cm}p{3.2cm}}
\toprule
Outcome & Generator & Problem & Initial response $R_0$ & Critique $F$ & Final response $R_f$ \\
\midrule
""" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # --- binary results: CPU baselines plus any trained encoders
    res_dir = os.path.join(rd, "results")
    base = json.load(open(os.path.join(res_dir, "baselines_binary.json")))
    entries = [(NAMES.get(k, k), v) for k, v in base["models"].items()]
    rows = []
    for name, v in entries:
        ci = v["ci95"]["accuracy"]
        p = v.get("mcnemar_vs_tfidf_lr")
        ptxt = "--" if not p else (f"{p['p_value']:.3f}" if p["p_value"] >= 0.001 else "$<$0.001")
        rows.append(f"{name} & {v['accuracy']:.3f} [{ci[0]:.3f}, {ci[1]:.3f}] & {v['macro_f1']:.3f} & "
                    f"{v['weighted_f1']:.3f} & {v['auc']:.3f} & {ptxt} \\\\" if "auc" in v else
                    f"{name} & {v['accuracy']:.3f} [{ci[0]:.3f}, {ci[1]:.3f}] & {v['macro_f1']:.3f} & {v['weighted_f1']:.3f} & -- & {ptxt} \\\\")
    write(a.out, "tab_binary_results.tex", r"""\begin{tabular}{lccccc}
\toprule
Predictor & Accuracy [95\% CI] & Macro F1 & Weighted F1 & AUC-ROC & $p$ vs.\ TF-IDF \\
\midrule
""" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    numbers["binary_results"] = {name: {k: v[k] for k in ("accuracy", "macro_f1", "weighted_f1", "auc") if k in v}
                                 for name, v in entries}
    numbers["test_n"] = base["test_n"]
    encoder_tables(rd, res_dir, a.out, numbers)
    routing_and_macros(rd, res_dir, a.out, numbers)
    json.dump(numbers, open(os.path.join(a.out, "numbers.json"), "w"), indent=2)
    print(f"wrote tables to {a.out}")
    print(json.dumps(numbers, indent=2)[:2500])


if __name__ == "__main__":
    main()
